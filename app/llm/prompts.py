def get_system_prompt(agent: str, context: dict | None = None) -> str:
    template = PROMPTS[agent]
    if context:
        try:
            return template.format(**context)
        except (KeyError, IndexError):
            # Templates without placeholders, or partial context, pass through.
            return template
    return template
